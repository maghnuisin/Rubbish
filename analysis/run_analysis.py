"""Reproduces the Grit-vs-Decapitator-P analysis from the recordings in analysis/data.

Steps:
1. Measure Decapitator P's harmonics (H1..H40) every 0.1 Drive from Logic recordings
   of a sine swept through it (Drive automated 0 -> 10 over 42.67 s).
2. Render the same sweep through every historical version of Rubbish's Grit Character
   (a NumPy copy of the plugin's maths) and measure it the same way.
3. Score each version against P and draw the figures used in docs/case-study.md.

Run:  .venv/bin/python run_analysis.py
"""

from pathlib import Path

import numpy as np
import soundfile as sf

from rubbish_analysis import figures, grit_model, harmonics

HERE = Path(__file__).parent
DATA = HERE / "data"
OUTPUT = HERE / "output"
IMAGES = HERE.parent / "docs" / "images"

SWEEP_SECONDS = 42.6667        # 16 bars at 90 bpm
INPUT_PEAK_DBFS = -13.0        # level at which the sine reached the plugins in Logic
DECAP_TO_RUBBISH_DB = 3.6      # one Decapitator Drive step = 3.6 dB of Rubbish Drive
DRIVE_STEPS = np.round(np.arange(0.1, 10.0001, 0.1), 1)

RECORDINGS = {
    "44hz-push-off": ("p-sweep-44hz-punish-off.flac", 0.0),
    "175hz-push-off": ("p-sweep-175hz-punish-off.flac", 0.0),
    "44hz-push-on": ("p-sweep-44hz-punish-on.flac", 1.0),
}


def times_for(drive_steps):
    return drive_steps / 10.0 * SWEEP_SECONDS


def measure_reference(filename):
    signal, rate = sf.read(DATA / filename)
    f0 = harmonics.estimate_fundamental(signal, rate)
    return f0, rate, harmonics.harmonic_map(signal, rate, f0, times_for(DRIVE_STEPS))


def measure_model(voicing, f0, rate, push):
    t = np.arange(int((SWEEP_SECONDS + 3) * rate)) / rate
    sine = 10 ** (INPUT_PEAK_DBFS / 20) * np.sin(2 * np.pi * f0 * t)
    drive_db = np.clip(t / SWEEP_SECONDS, 0, 1) * 10 * DECAP_TO_RUBBISH_DB
    rendered = grit_model.render(sine, rate, drive_db, voicing, push)
    return harmonics.harmonic_map(rendered, rate, f0, times_for(DRIVE_STEPS))


def band_db(levels, first, last):
    """Combined level of harmonics first..last (1-based), in dB relative to the fundamental."""
    power = np.nansum(10 ** (levels[:, first - 1:last] / 10), axis=1)
    return 10 * np.log10(power + 1e-12)


def score(reference, model):
    """Mean absolute dB error vs the reference over the whole Drive range."""
    def mean_error(a, b):
        return float(np.nanmean(np.abs(a - b)))
    return {
        "H2-H5 (dB)": mean_error(reference[:, 1:5], model[:, 1:5]),
        "H6-H19 band (dB)": mean_error(band_db(reference, 6, 19), band_db(model, 6, 19)),
        "H20-H40 band (dB)": mean_error(band_db(reference, 20, 40), band_db(model, 20, 40)),
        "THD (points)": mean_error(thd_curve(reference), thd_curve(model)),
    }


def thd_curve(levels):
    return np.array([harmonics.thd_percent(row) for row in levels])


def save_map(path, levels):
    header = "drive," + ",".join(f"H{k}" for k in range(1, levels.shape[1] + 1))
    np.savetxt(path, np.column_stack([DRIVE_STEPS, levels]), delimiter=",", header=header, comments="", fmt="%.2f")


def write_summary(scores):
    lines = ["# Grit vs Decapitator P: fit summary", "",
             "Mean absolute error against P over Drive 0.1-10 (lower is better). Generated by run_analysis.py.", ""]
    for condition, by_version in scores.items():
        metrics = list(next(iter(by_version.values())).keys())
        lines += [f"## {condition}", "", "| Grit version | " + " | ".join(metrics) + " |",
                  "|---" * (len(metrics) + 1) + "|"]
        for version, values in by_version.items():
            lines.append(f"| {version} | " + " | ".join(f"{values[m]:.1f}" for m in metrics) + " |")
        lines.append("")
    (OUTPUT / "fit-summary.md").write_text("\n".join(lines))


def main():
    OUTPUT.mkdir(exist_ok=True)
    IMAGES.mkdir(parents=True, exist_ok=True)
    maps, scores = {}, {}
    for condition, (filename, push) in RECORDINGS.items():
        f0, rate, reference = measure_reference(filename)
        print(f"{condition}: P measured at {f0:.3f} Hz")
        maps[condition] = {"Decapitator P": reference}
        save_map(OUTPUT / f"p-{condition}.csv", reference)
        scores[condition] = {}
        for version, voicing in grit_model.GRIT_VERSIONS.items():
            model = measure_model(voicing, f0, rate, push)
            maps[condition][version] = model
            scores[condition][version] = score(reference, model)
            save_map(OUTPUT / f"grit-{version.split()[0]}-{condition}.csv", model)
    write_summary(scores)
    figures.draw_all(maps, scores, DRIVE_STEPS, thd_curve, IMAGES)
    print((OUTPUT / "fit-summary.md").read_text())


if __name__ == "__main__":
    main()
